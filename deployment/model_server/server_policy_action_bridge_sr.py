from __future__ import annotations

import argparse
import logging
import math
import socket
import threading
import time
from contextlib import nullcontext
from pathlib import Path
from typing import Any, Sequence

import torch

from deployment.model_server.server_policy import build_policy_server_metadata
from deployment.model_server.tools.websocket_policy_server import WebsocketPolicyServer
from starVLA.model.framework.base_framework import baseframework
from starVLA.model.framework.latent_world.runtime.output_mapper import map_policy_infer_output


ROUTE_ORDER = [
    "base_ref",
    "vlm_only",
    "world_only",
    "upstream_joint",
    "flow_only",
    "full",
]
ROUTE_TO_OFFSET = {name: idx for idx, name in enumerate(ROUTE_ORDER)}


def _autocast_for(device: torch.device, dtype: torch.dtype):
    if device.type == "cuda" and torch.cuda.is_available():
        return torch.autocast("cuda", dtype=dtype)
    return nullcontext()


def _move_batch(batch, device: torch.device):
    out = {}
    for key, value in batch.items():
        if torch.is_tensor(value):
            out[key] = value.to(device=device, non_blocking=True)
        else:
            out[key] = value
    return batch.__class__(out)


def _load_policy(
    ckpt_path: str,
    *,
    device: str,
    use_bf16: bool,
):
    start = time.perf_counter()
    logging.info("Loading checkpoint on CPU: %s", ckpt_path)
    policy = baseframework.from_pretrained(ckpt_path)
    logging.info("Checkpoint materialized in %.1fs: %s", time.perf_counter() - start, ckpt_path)

    if use_bf16:
        logging.info("Casting checkpoint to bfloat16: %s", ckpt_path)
        policy = policy.to(torch.bfloat16)

    logging.info("Moving checkpoint to %s: %s", device, ckpt_path)
    policy = policy.to(device).eval()
    if str(device).startswith("cuda") and torch.cuda.is_available():
        torch.cuda.synchronize(torch.device(device))
    logging.info("Policy ready on %s (total %.1fs)", device, time.perf_counter() - start)
    return policy


def _first_param_device(module) -> torch.device:
    return next(module.parameters()).device


def _check_policy_compatibility(base_policy, stage_policy) -> None:
    base = base_policy.policy_backend
    stage = stage_policy.policy_backend

    checks = {
        "num_action_queries": (int(base.num_action_queries), int(stage.num_action_queries)),
        "flow_action_num_queries": (
            int(base.flow_action_query.shape[0]),
            int(stage.flow_action_query.shape[0]),
        ),
        "placeholder_token_id": (int(base.placeholder_token_id), int(stage.placeholder_token_id)),
        "action_horizon": (int(base.flow.action_horizon), int(stage.flow.action_horizon)),
        "state_dim": (int(base.flow.config.state_dim), int(stage.flow.config.state_dim)),
        "action_dim": (int(base.flow.config.action_dim), int(stage.flow.config.action_dim)),
        "num_vision_tokens": (
            int(base.flow.config.num_vision_tokens),
            int(stage.flow.config.num_vision_tokens),
        ),
        "vision_dim": (int(base.flow.config.vision_dim), int(stage.flow.config.vision_dim)),
        "horizon_sec": (float(base.flow.config.horizon_sec), float(stage.flow.config.horizon_sec)),
    }

    bad = []
    for name, (a, b) in checks.items():
        if isinstance(a, float) or isinstance(b, float):
            equal = math.isclose(float(a), float(b), rel_tol=0.0, abs_tol=1e-12)
        else:
            equal = a == b
        if not equal:
            bad.append((name, a, b))

    if bad:
        text = "\n".join(f"  {name}: Base={a!r}, Stage={b!r}" for name, a, b in bad)
        raise RuntimeError("Base/Stage policy interface mismatch:\n" + text)

    logging.info("Base/Stage policy interface compatibility check passed.")


class ActionBridgeEngine:
    """Closed-loop realization of the existing six-route action intervention.

    The exact route definition mirrors the prior offline action-coupling probe:

      base_ref       : F_B(H_B, Future_B)
      vlm_only       : F_B(H_k, Future_B)
      world_only     : F_B(H_B, Future_k)
      upstream_joint : F_B(H_k, Future_k)
      flow_only      : F_k(H_B, Future_B)
      full           : F_k(H_k, Future_k)

    Important matching detail:
    `h_t` is always generated by the Base LAM visual encoder and is reused for
    Base/Stage future decoding, exactly matching the offline analysis where all
    routes used Base `h_t`.
    """

    def __init__(
        self,
        *,
        base_policy,
        stage_policy,
        seed: int = 2026,
    ) -> None:
        self.base_policy = base_policy
        self.stage_policy = stage_policy
        self.base_backend = base_policy.policy_backend
        self.stage_backend = stage_policy.policy_backend
        self.base_device = _first_param_device(self.base_backend)
        self.stage_device = _first_param_device(self.stage_backend)
        self.infer_batch_builder = base_policy.policy_infer_batch_builder
        self.config = base_policy.config
        self.processor = getattr(base_policy, "processor", None)
        self._lock = threading.Lock()
        self.seed = int(seed)

        _check_policy_compatibility(base_policy, stage_policy)

        # Independent, identically seeded RNG streams per route. This makes the
        # route evaluations less sensitive to evaluation order while preserving
        # stochastic Flow sampling inside each route.
        self._rng_state_cpu: dict[str, torch.Tensor] = {}
        self._cuda_devices = []
        if torch.cuda.is_available():
            for dev in (self.base_device, self.stage_device):
                if dev.type == "cuda" and str(dev) not in {str(x) for x in self._cuda_devices}:
                    self._cuda_devices.append(dev)
        self._rng_state_cuda: dict[str, dict[str, torch.Tensor]] = {}
        outer_cpu = torch.random.get_rng_state()
        outer_cuda = {
            str(dev): torch.cuda.get_rng_state(dev).clone()
            for dev in self._cuda_devices
        }
        try:
            for route in ROUTE_ORDER:
                torch.manual_seed(self.seed)
                if torch.cuda.is_available():
                    torch.cuda.manual_seed_all(self.seed)
                self._rng_state_cpu[route] = torch.random.get_rng_state().clone()
                self._rng_state_cuda[route] = {
                    str(dev): torch.cuda.get_rng_state(dev).clone()
                    for dev in self._cuda_devices
                }
        finally:
            torch.random.set_rng_state(outer_cpu)
            for dev in self._cuda_devices:
                torch.cuda.set_rng_state(outer_cuda[str(dev)], dev)

    def _extract_base_h_t(self, base_batch):
        backend = self.base_backend
        with torch.inference_mode(), _autocast_for(self.base_device, torch.bfloat16):
            features = backend.lam.extract_vision_features(base_batch["primary_image"])
        if features is None or features.ndim != 4:
            raise RuntimeError(
                "Expected Base LAM visual features [B,T,K,D], got "
                f"{None if features is None else tuple(features.shape)}"
            )
        return features[:, 0, :, :].detach()

    def _condition_from(self, backend, batch, *, h_t, label: str):
        device = _first_param_device(backend)
        vlm_dtype = backend.model_cfg.vlm_dtype

        act_query, flow_query = backend._prepare_queries(
            device=device,
            vlm_stage_dtype=vlm_dtype,
        )

        with torch.inference_mode(), _autocast_for(device, vlm_dtype):
            out = backend._run_vlm_stage(
                input_ids=batch["input_ids"],
                attention_mask=batch["attention_mask"],
                pixel_values=batch["pixel_values"],
                image_grid_thw=batch["image_grid_thw"],
                act_placeholder_mask=batch["act_placeholder_mask"],
                flow_placeholder_mask=batch["flow_placeholder_mask"],
                act_query=act_query,
                flow_query=flow_query,
            )

        h_vlm = out["h_vlm"].detach()
        pred_latent = out["pred_latent"].detach()
        h_t_local = h_t.to(device=device, non_blocking=True)

        if bool(backend.model_cfg.future_prediction):
            with torch.inference_mode(), _autocast_for(device, torch.bfloat16):
                h_future = backend._decode_future_tokens_strict_single_query(
                    h_t=h_t_local,
                    pred_action_emb=pred_latent,
                    source=f"ActionBridge/{label}",
                )
        else:
            h_future = h_t_local

        return h_vlm.detach(), h_future.detach()

    @staticmethod
    def _move_tensor(x: torch.Tensor, device: torch.device) -> torch.Tensor:
        return x.to(device=device, non_blocking=True)

    def _sample_route(
        self,
        *,
        route: str,
        examples: Sequence[dict[str, Any]],
        guidance_scale: float | None,
        num_inference_steps: int | None,
        return_intermediates: bool,
    ):
        if route not in ROUTE_TO_OFFSET:
            raise ValueError(f"Unknown bridge route: {route}")
        if len(examples) == 0:
            raise ValueError("Action bridge requires at least one inference example.")

        # Use the Base batch builder/processor for ALL routes. This mirrors the
        # offline probe's fixed-input construction and avoids stage-specific
        # preprocessing from becoming an untracked intervention variable.
        base_batch = self.infer_batch_builder.build_infer_batch(examples)
        if _first_param_device(self.base_backend) != self.base_device:
            raise RuntimeError("Base backend device changed unexpectedly.")
        stage_batch = (
            base_batch
            if self.stage_device == self.base_device
            else _move_batch(base_batch, self.stage_device)
        )

        # The previous offline action probe fixed h_t to Base for every route.
        h_t_base = self._extract_base_h_t(base_batch)

        need_base_cond = route in {
            "base_ref",
            "vlm_only",
            "world_only",
            "flow_only",
        }
        need_stage_cond = route in {
            "vlm_only",
            "world_only",
            "upstream_joint",
            "full",
        }

        base_h_vlm = base_future = None
        stage_h_vlm = stage_future = None

        if need_base_cond:
            base_h_vlm, base_future = self._condition_from(
                self.base_backend,
                base_batch,
                h_t=h_t_base,
                label="Base",
            )

        if need_stage_cond:
            stage_h_vlm, stage_future = self._condition_from(
                self.stage_backend,
                stage_batch,
                h_t=h_t_base,
                label="Stage",
            )

        if route == "base_ref":
            flow_backend = self.base_backend
            h_vlm = base_h_vlm
            h_future = base_future
        elif route == "vlm_only":
            flow_backend = self.base_backend
            h_vlm = stage_h_vlm
            h_future = base_future
        elif route == "world_only":
            flow_backend = self.base_backend
            h_vlm = base_h_vlm
            h_future = stage_future
        elif route == "upstream_joint":
            flow_backend = self.base_backend
            h_vlm = stage_h_vlm
            h_future = stage_future
        elif route == "flow_only":
            flow_backend = self.stage_backend
            h_vlm = base_h_vlm
            h_future = base_future
        elif route == "full":
            flow_backend = self.stage_backend
            h_vlm = stage_h_vlm
            h_future = stage_future
        else:  # pragma: no cover
            raise AssertionError(route)

        assert h_vlm is not None and h_future is not None
        flow_device = _first_param_device(flow_backend.flow)
        flow_batch = base_batch if flow_device == self.base_device else _move_batch(base_batch, flow_device)

        if guidance_scale is None:
            guidance_scale = float(flow_backend.flow.config.cfg_guidance_scale)
        if num_inference_steps is None:
            num_inference_steps = int(flow_backend.flow.config.num_inference_steps)

        attention_mask = flow_batch["attention_mask"] == 1
        h_t_for_flow = self._move_tensor(h_t_base, flow_device)
        h_vlm_for_flow = self._move_tensor(h_vlm, flow_device)
        h_future_for_flow = self._move_tensor(h_future, flow_device)

        # Match LatentWorldPolicyBackend.predict_action: Flow executes in float32.
        with torch.inference_mode(), _autocast_for(flow_device, torch.float32):
            actions = flow_backend.flow.sample_actions_cfg(
                h_t=h_t_for_flow,
                h_t1_star=h_future_for_flow,
                h_vlm=h_vlm_for_flow,
                state=flow_batch["state"],
                state_mask=flow_batch["state_mask"],
                action_hz=flow_batch["action_hz"],
                embodiment_id=flow_batch["embodiment_id"],
                cfg_scale=float(guidance_scale),
                num_inference_steps=int(num_inference_steps),
                attention_mask=attention_mask,
                return_padded=False,
            )

        # Same action-length contract as the standard runner.
        hz_values = flow_batch["action_hz"].detach().cpu().tolist()
        horizon_sec = float(flow_backend.flow.config.horizon_sec)
        expected_lens = [int(math.floor(horizon_sec * float(hz))) for hz in hz_values]
        if len(set(expected_lens)) != 1:
            raise RuntimeError(f"Mixed expected action lengths in one bridge batch: {expected_lens}")
        expected_len = int(expected_lens[0])
        if int(actions.shape[1]) != expected_len:
            raise RuntimeError(
                "Bridge action length mismatch: "
                f"actual={int(actions.shape[1])}, expected={expected_len}"
            )

        intermediates = None
        if return_intermediates:
            num_tokens = int(h_t_base.shape[1])
            hw = int(num_tokens ** 0.5)
            if hw * hw != num_tokens:
                hw = 16
            intermediates = {
                "h_t": h_t_base.detach().cpu(),
                "h_t1_pred": h_future.detach().cpu(),
                "vision_tokens_hw": torch.tensor([hw, hw]).repeat(int(actions.shape[0]), 1),
            }

        return map_policy_infer_output(actions, intermediates=intermediates)

    def predict_route(self, route: str, examples, **kwargs):
        # WebsocketPolicyServer may pass protocol bookkeeping keys through **msg.
        return_intermediates = bool(kwargs.pop("return_intermediates", False))
        guidance_scale = kwargs.pop("guidance_scale", None)
        num_inference_steps = kwargs.pop("num_inference_steps", None)
        kwargs.pop("type", None)
        kwargs.pop("request_id", None)
        kwargs.pop("payload", None)
        if kwargs:
            logging.debug("Ignoring extra bridge inference kwargs: %s", sorted(kwargs))

        with self._lock:
            outer_cpu = torch.random.get_rng_state()
            outer_cuda = {
                str(dev): torch.cuda.get_rng_state(dev).clone()
                for dev in self._cuda_devices
            }
            try:
                torch.random.set_rng_state(self._rng_state_cpu[route])
                for dev in self._cuda_devices:
                    torch.cuda.set_rng_state(self._rng_state_cuda[route][str(dev)], dev)

                result = self._sample_route(
                    route=route,
                    examples=examples,
                    guidance_scale=guidance_scale,
                    num_inference_steps=num_inference_steps,
                    return_intermediates=return_intermediates,
                )

                self._rng_state_cpu[route] = torch.random.get_rng_state().clone()
                self._rng_state_cuda[route] = {
                    str(dev): torch.cuda.get_rng_state(dev).clone()
                    for dev in self._cuda_devices
                }
                return result
            finally:
                torch.random.set_rng_state(outer_cpu)
                for dev in self._cuda_devices:
                    torch.cuda.set_rng_state(outer_cuda[str(dev)], dev)


class RoutePolicy:
    def __init__(self, engine: ActionBridgeEngine, route: str):
        self.engine = engine
        self.route = route
        self.config = engine.config
        self.processor = engine.processor

    @torch.inference_mode()
    def predict_action(self, examples, **kwargs):
        return self.engine.predict_route(self.route, examples, **kwargs)


def build_argparser():
    p = argparse.ArgumentParser(
        description="Serve the six-route LaWAM closed-loop action bridge intervention."
    )
    p.add_argument("--base_ckpt_path", required=True)
    p.add_argument("--stage_ckpt_path", required=True)
    p.add_argument("--port_base", type=int, default=6694)
    p.add_argument("--routes", nargs="+", choices=ROUTE_ORDER, default=ROUTE_ORDER)
    p.add_argument("--use_bf16", action="store_true")
    p.add_argument("--base_device", default="cuda:0")
    p.add_argument("--stage_device", default="cuda:0")
    p.add_argument("--seed", type=int, default=2026)
    p.add_argument("--idle_timeout", type=int, default=-1)
    return p


def main(args) -> None:
    base_ckpt = str(Path(args.base_ckpt_path).expanduser().resolve())
    stage_ckpt = str(Path(args.stage_ckpt_path).expanduser().resolve())

    logging.info("Action bridge Base checkpoint : %s", base_ckpt)
    logging.info("Action bridge Stage checkpoint: %s", stage_ckpt)
    logging.info("Base device=%s Stage device=%s", args.base_device, args.stage_device)

    base_policy = _load_policy(
        base_ckpt,
        device=args.base_device,
        use_bf16=bool(args.use_bf16),
    )
    stage_policy = _load_policy(
        stage_ckpt,
        device=args.stage_device,
        use_bf16=bool(args.use_bf16),
    )

    engine = ActionBridgeEngine(
        base_policy=base_policy,
        stage_policy=stage_policy,
        seed=int(args.seed),
    )

    hostname = socket.gethostname()
    try:
        local_ip = socket.gethostbyname(hostname)
    except OSError:
        local_ip = "unknown"
    logging.info("Creating bridge servers (host=%s ip=%s)", hostname, local_ip)

    threads: list[threading.Thread] = []
    for route in args.routes:
        route_policy = RoutePolicy(engine, route)
        port = int(args.port_base) + int(ROUTE_TO_OFFSET[route])
        metadata = build_policy_server_metadata(
            route_policy,
            # ModelClient uses this path only to check consistency and read
            # normalization/action config. We deliberately anchor those to Base.
            ckpt_path=base_ckpt,
            server_type="starvla_action_bridge",
            env="generic",
            supported_eval_envs=["libero"],
            extra_metadata={
                "bridge_route": route,
                "bridge_base_ckpt_path": base_ckpt,
                "bridge_stage_ckpt_path": stage_ckpt,
                "bridge_seed": int(args.seed),
                "bridge_h_t_source": "Base",
            },
        )
        server = WebsocketPolicyServer(
            policy=route_policy,
            host="0.0.0.0",
            port=port,
            idle_timeout=int(args.idle_timeout),
            metadata=metadata,
        )
        thread = threading.Thread(
            target=server.serve_forever,
            name=f"bridge-{route}-{port}",
            daemon=False,
        )
        thread.start()
        threads.append(thread)
        logging.info("Bridge route %-16s -> port %d", route, port)

    for thread in threads:
        thread.join()


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO, force=True)
    main(build_argparser().parse_args())