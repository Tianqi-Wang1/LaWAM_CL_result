#!/usr/bin/env bash
set -euo pipefail

source /apps/miniconda3/etc/profile.d/conda.sh
source /home/jincai_guo/tianqi/CVPR2027/setup_paths.sh
conda activate /home/jincai_guo/tianqi/CVPR2027/envs/lawam

ROOT="/home/jincai_guo/tianqi/CVPR2027/LaWAM"
cd "${ROOT}"

ANALYSIS_SCRIPT="${ROOT}/scripts/analyze_flow_full_vs_lora_alignment.py"

BASE_CKPT="${BASE_CKPT:-/home/jincai_guo/tianqi/CVPR2027/checkpoints/lawam_cl/libero_goal/seqft/20260807_124027+base_t0_5_10k_4gpu_bs32_ga2/final_model/pytorch_model.pt}"

# -----------------------------------------------------------------------------
# Strict Frozen-Upstream + Full-Flow T9 checkpoint.
# Prefer the pointer generated by run_libero_goal_full_flow_t9_retrain_v1.sh.
# -----------------------------------------------------------------------------
FULL_ROOT="/home/jincai_guo/tianqi/CVPR2027/checkpoints/lawam_cl/libero_goal/full_flow_t9_retrain"
FULL_POINTER="${FULL_ROOT}/LATEST_T9_FULL_FLOW.txt"

if [ -n "${FULL_T9_CKPT:-}" ]; then
    echo "[INFO] Using explicitly supplied FULL_T9_CKPT"
elif [ -f "${FULL_POINTER}" ]; then
    FULL_T9_CKPT=$(head -n 1 "${FULL_POINTER}")
else
    FULL_RUN=$(find "${FULL_ROOT}/heads" \
        -maxdepth 1 \
        -type d \
        -name '*+t9_*step_*gpu_bs*_ga*_full_flow_only_from_base' \
        | sort \
        | tail -n 1)

    if [ -z "${FULL_RUN}" ]; then
        echo "[ERROR] Strict Full-Flow T9 checkpoint not found."
        echo "        Run scripts/run_libero_goal_full_flow_t9_retrain_v1.sh first."
        exit 1
    fi

    FULL_T9_CKPT="${FULL_RUN}/final_model/pytorch_model.pt"
fi

# -----------------------------------------------------------------------------
# Existing r8 / alpha8 / lr1e-4 T9 merged checkpoint.
# This is the completed Flow-LoRA v1 result with T9 SR = 0.34.
# -----------------------------------------------------------------------------
if [ -z "${LORA_R8_T9_CKPT:-}" ]; then
    R8_ROOT="/home/jincai_guo/tianqi/CVPR2027/checkpoints/lawam_cl/libero_goal/flow_lora_oracle/r8/heads"

    R8_RUN=$(find "${R8_ROOT}" \
        -maxdepth 1 \
        -type d \
        -name '*+cl4_t9_2000step_4gpu_bs64_ga1_flow_lora_r8_from_base' \
        | sort \
        | tail -n 1)

    if [ -z "${R8_RUN}" ]; then
        echo "[ERROR] r8 T9 LoRA run not found under:"
        echo "        ${R8_ROOT}"
        echo "        You can supply it manually with:"
        echo "        LORA_R8_T9_CKPT=/path/to/pytorch_model_merged.pt"
        exit 1
    fi

    LORA_R8_T9_CKPT="${R8_RUN}/final_model/pytorch_model_merged.pt"
fi

for required in \
    "${ANALYSIS_SCRIPT}" \
    "${BASE_CKPT}" \
    "${FULL_T9_CKPT}" \
    "${LORA_R8_T9_CKPT}"
do
    if [ ! -f "${required}" ]; then
        echo "[ERROR] Missing required file:"
        echo "        ${required}"
        exit 1
    fi
done

ANALYSIS_GPU="${ANALYSIS_GPU:-0}"
export CUDA_VISIBLE_DEVICES="${ANALYSIS_GPU}"

TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
OUTPUT_DIR="${ROOT}/results/analysis/lawam_cl/libero_goal/t9_full_vs_lora_r8_alignment/${TIMESTAMP}"
mkdir -p "${OUTPUT_DIR}"

cat > "${OUTPUT_DIR}/CHECKPOINTS.txt" <<EOF2
Base:
${BASE_CKPT}

Strict Frozen-Upstream Full-Flow T9:
${FULL_T9_CKPT}

Flow-LoRA r8/a8/lr1e-4 T9 (observed SR=0.34):
${LORA_R8_T9_CKPT}
EOF2

cat > "${OUTPUT_DIR}/PROTOCOL.txt" <<EOF2
Strict T9 update-alignment diagnostic.

Compare the same formal Base Flow against:
  1. Frozen-Upstream + Full-Flow T9 adaptation
  2. Frozen-Upstream + Flow-LoRA r8/a8/lr1e-4 T9 adaptation

Definitions:
  Delta_F_full = F_full_T9 - F_base
  Delta_F_r8   = F_lora_r8_T9 - F_base

Primary metrics:
  - weighted cosine alignment
  - update norm ratio
  - projection coefficient onto the Full-Flow update
  - relative residual ||Delta_F_r8 - Delta_F_full|| / ||Delta_F_full||

The analysis is reported for:
  - the entire Flow
  - the 96 current LoRA target weights only
  - component groups
  - transformer blocks

Observed behavior reference:
  Flow-LoRA r8 T9 SR = 0.34
EOF2

echo "=========================================================="
echo " T9 Strict Full-Flow vs Flow-LoRA r8 Alignment"
echo "=========================================================="
echo "Analysis GPU : ${ANALYSIS_GPU}"
echo "Base         : ${BASE_CKPT}"
echo "Full T9      : ${FULL_T9_CKPT}"
echo "LoRA r8 T9   : ${LORA_R8_T9_CKPT}"
echo "Output       : ${OUTPUT_DIR}"
echo "=========================================================="

python "${ANALYSIS_SCRIPT}" \
    --base "${BASE_CKPT}" \
    --full "${FULL_T9_CKPT}" \
    --candidate r8_a8_lr1e-4 "${LORA_R8_T9_CKPT}" \
    --device cuda:0 \
    --output-dir "${OUTPUT_DIR}" \
    2>&1 | tee "${OUTPUT_DIR}/analysis.log"

echo
echo "=========================================================="
echo " T9 Full vs r8 alignment analysis complete"
echo "=========================================================="
echo "Main summary:"
echo "  ${OUTPUT_DIR}/SUMMARY.txt"
echo "Overview:"
echo "  ${OUTPUT_DIR}/alignment_overview.csv"
echo "Components:"
echo "  ${OUTPUT_DIR}/component_alignment.csv"
echo "Blocks:"
echo "  ${OUTPUT_DIR}/block_alignment.csv"
echo "Per tensor:"
echo "  ${OUTPUT_DIR}/per_tensor_alignment.csv"
echo "Protocol:"
echo "  ${OUTPUT_DIR}/PROTOCOL.txt"
echo "=========================================================="